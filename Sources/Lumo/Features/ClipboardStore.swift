import AppKit
import Carbon
import LumoCore
import SwiftUI

/// Local clipboard history with pins, search and a ⇧⌘V panel. Password-manager copies
/// (marked Concealed/Transient) are never recorded.
@MainActor
final class ClipboardStore: ObservableObject {
    private enum Key {
        static let enabled = "clipboard.enabled"
        static let limit = "clipboard.limit"
        static let hotkey = "clipboard.hotkey"
    }

    private static let pollInterval: TimeInterval = 1
    private static let maxImageSide: CGFloat = 2560
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    @Published private(set) var entries: [ClipEntry] = []
    @Published var isEnabled: Bool { didSet { store.set(isEnabled, forKey: Key.enabled); update() } }
    @Published var limit: Int { didSet { store.set(limit, forKey: Key.limit) } }
    @Published var panelHotkey: Bool { didSet { store.set(panelHotkey, forKey: Key.hotkey); update() } }

    let folder: URL
    private let store: UserDefaults
    private let hotKeys = HotKeyCenter()
    private lazy var panel = ClipboardPanelController(store: self)
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var saveTask: Task<Void, Never>?

    init(store: UserDefaults) {
        store.register(defaults: [Key.limit: 200, Key.hotkey: true])
        self.store = store
        isEnabled = store.bool(forKey: Key.enabled)
        limit = store.integer(forKey: Key.limit)
        panelHotkey = store.bool(forKey: Key.hotkey)
        folder = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Lumo/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        load()
        update()
    }

    var sortedEntries: [ClipEntry] { ClipboardHistory.sorted(entries) }

    func update() {
        timer?.invalidate()
        timer = nil
        hotKeys.unregisterAll()
        guard isEnabled else { return }
        lastChange = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        if panelHotkey {
            hotKeys.register(.clipboard) { [weak self] in self?.panel.toggle() }
        }
    }

    func showPanel() { panel.toggle() }

    // MARK: Actions

    func copy(_ entry: ClipEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text: pasteboard.setString(entry.text ?? "", forType: .string)
        case .files: pasteboard.writeObjects((entry.files ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let url = imageURL(for: entry), let image = NSImage(contentsOf: url) { pasteboard.writeObjects([image]) }
        }
        lastChange = pasteboard.changeCount
    }

    /// Puts the entry on the clipboard and presses ⌘V in the frontmost app.
    func paste(_ entry: ClipEntry) {
        copy(entry)
        Paster.pressPaste()
    }

    func togglePin(_ entry: ClipEntry) {
        entries = entries.map { $0.id == entry.id ? $0.withPinned(!$0.pinned) : $0 }
        scheduleSave()
    }

    func delete(_ entry: ClipEntry) {
        entries = entries.filter { $0.id != entry.id }
        removeImage(of: entry)
        scheduleSave()
    }

    func clearUnpinned() {
        entries.filter { !$0.pinned }.forEach(removeImage(of:))
        entries = entries.filter(\.pinned)
        scheduleSave()
    }

    func imageURL(for entry: ClipEntry) -> URL? {
        entry.imageFile.map { folder.appendingPathComponent($0) }
    }

    // MARK: Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        let entry: ClipEntry?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            entry = ClipEntry(kind: .files, files: urls.map(\.path), sourceApp: source)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            entry = ClipEntry(kind: .text, text: String(text.prefix(100_000)), sourceApp: source)
        } else if let image = NSImage(pasteboard: pasteboard), let file = saveImage(image) {
            entry = ClipEntry(kind: .image, imageFile: file, sourceApp: source)
        } else {
            entry = nil
        }
        guard let entry else { return }
        let result = ClipboardHistory.adding(entry, to: entries, limit: limit)
        entries = result.history
        result.dropped.forEach(removeImage(of:))
        scheduleSave()
    }

    private func saveImage(_ image: NSImage) -> String? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        let scale = min(1, Self.maxImageSide / CGFloat(max(bitmap.pixelsWide, bitmap.pixelsHigh, 1)))
        let resized = scale < 1 ? Self.resize(bitmap, scale: scale) : bitmap
        guard let png = resized.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        do {
            try png.write(to: folder.appendingPathComponent(name), options: .atomic)
            return name
        } catch {
            return nil
        }
    }

    private static func resize(_ bitmap: NSBitmapImageRep, scale: CGFloat) -> NSBitmapImageRep {
        let width = Int(CGFloat(bitmap.pixelsWide) * scale), height = Int(CGFloat(bitmap.pixelsHigh) * scale)
        guard let cgImage = bitmap.cgImage,
              let context = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                      space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                      bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue)
        else { return bitmap }
        context.interpolationQuality = .high
        context.draw(cgImage, in: CGRect(x: 0, y: 0, width: width, height: height))
        return context.makeImage().map(NSBitmapImageRep.init(cgImage:)) ?? bitmap
    }

    private func removeImage(of entry: ClipEntry) {
        if let url = imageURL(for: entry) { try? FileManager.default.removeItem(at: url) }
    }

    // MARK: Persistence

    private var historyFile: URL { folder.appendingPathComponent("clipboard.json") }

    private func load() {
        guard let data = try? Data(contentsOf: historyFile) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        entries = (try? decoder.decode([ClipEntry].self, from: data)) ?? []
    }

    private func scheduleSave() {
        saveTask?.cancel()
        let snapshot = entries
        let file = historyFile
        saveTask = Task {
            try? await Task.sleep(for: .milliseconds(600))
            guard !Task.isCancelled else { return }
            await Task.detached(priority: .utility) {
                let encoder = JSONEncoder()
                encoder.dateEncodingStrategy = .iso8601
                if let data = try? encoder.encode(snapshot) { try? data.write(to: file, options: .atomic) }
            }.value
        }
    }
}

/// Synthesizes ⌘V (needs Accessibility).
enum Paster {
    static func pressPaste() {
        let source = CGEventSource(stateID: .hidSystemState)
        for isDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: isDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: InputTap.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }

    static func pressBackspace(times: Int) {
        let source = CGEventSource(stateID: .hidSystemState)
        for _ in 0..<times {
            for isDown in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_Delete), keyDown: isDown) else { continue }
                event.setIntegerValueField(.eventSourceUserData, value: InputTap.syntheticMarker)
                event.post(tap: .cghidEventTap)
            }
        }
    }
}

// MARK: - ⇧⌘V panel

/// A panel that can take keyboard focus without activating Lumo, so ⌘V lands in the user's app.
final class KeyPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

@MainActor
final class ClipboardPanelController: NSObject, NSWindowDelegate {
    private unowned let store: ClipboardStore
    private var panel: KeyPanel?

    init(store: ClipboardStore) {
        self.store = store
    }

    func toggle() {
        if let panel, panel.isVisible { return close() }
        let panel = self.panel ?? makePanel()
        self.panel = panel
        panel.contentView = NSHostingView(rootView: ClipboardPanelView(store: store, close: { [weak self] in self?.close() }))
        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { $0.frame.contains(mouse) } ?? NSScreen.main
        let size = CGSize(width: 380, height: 460)
        var origin = CGPoint(x: mouse.x - 40, y: mouse.y - size.height - 10)
        if let visible = screen?.visibleFrame {
            origin.x = min(max(origin.x, visible.minX + 8), visible.maxX - size.width - 8)
            origin.y = min(max(origin.y, visible.minY + 8), visible.maxY - size.height - 8)
        }
        panel.setFrame(CGRect(origin: origin, size: size), display: true)
        panel.makeKeyAndOrderFront(nil)
    }

    func close() {
        panel?.orderOut(nil)
    }

    func windowDidResignKey(_ notification: Notification) { close() }

    private func makePanel() -> KeyPanel {
        let panel = KeyPanel(contentRect: .zero, styleMask: [.borderless, .nonactivatingPanel, .fullSizeContentView],
                             backing: .buffered, defer: true)
        panel.level = .popUpMenu
        panel.isOpaque = false
        panel.backgroundColor = .clear
        panel.hasShadow = true
        panel.collectionBehavior = [.canJoinAllSpaces, .transient, .fullScreenAuxiliary]
        panel.delegate = self
        return panel
    }
}

private struct ClipboardPanelView: View {
    @ObservedObject var store: ClipboardStore
    let close: () -> Void
    @State private var query = ""
    @State private var selection = 0
    @FocusState private var searchFocused: Bool

    var body: some View {
        let items = store.sortedEntries.filter { $0.matches(query) }
        VStack(spacing: 8) {
            HStack(spacing: 6) {
                Image(systemName: "magnifyingglass").foregroundStyle(.secondary)
                TextField("", text: $query).textFieldStyle(.plain).font(.system(size: 13)).focused($searchFocused)
                Text("⇧⌘V").font(.system(size: 10, weight: .bold, design: .rounded)).foregroundStyle(.tertiary)
            }
            .padding(.horizontal, 12).padding(.vertical, 9)
            .background(Capsule().fill(Color.primary.opacity(0.07)))
            ScrollViewReader { proxy in
                ScrollView {
                    LazyVStack(spacing: 3) {
                        ForEach(Array(items.enumerated()), id: \.element.id) { index, entry in
                            ClipRow(store: store, entry: entry, selected: index == selection)
                                .id(index)
                                .onTapGesture { paste(entry) }
                        }
                    }
                }
                .scrollIndicators(.never)
                .onChange(of: selection) { _, value in withAnimation(.easeOut(duration: 0.15)) { proxy.scrollTo(value) } }
            }
            if items.isEmpty {
                Text(store.entries.isEmpty ? "Clipboard is empty · Буфер пуст" : "No matches · Ничего не найдено")
                    .font(.system(size: 11)).foregroundStyle(.secondary).padding(.bottom, 20)
            }
        }
        .padding(12)
        .navyGlass(in: RoundedRectangle(cornerRadius: 22, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: 22, style: .continuous).strokeBorder(Color.white.opacity(0.14)))
        .onAppear { searchFocused = true }
        .onChange(of: query) { _, _ in selection = 0 }
        .onKeyPress(.downArrow) { selection = min(selection + 1, max(items.count - 1, 0)); return .handled }
        .onKeyPress(.upArrow) { selection = max(selection - 1, 0); return .handled }
        .onKeyPress(.return) {
            if items.indices.contains(selection) { paste(items[selection]) }
            return .handled
        }
        .onKeyPress(.escape) { close(); return .handled }
    }

    private func paste(_ entry: ClipEntry) {
        close()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { store.paste(entry) }
    }
}

struct ClipRow: View {
    @ObservedObject var store: ClipboardStore
    let entry: ClipEntry
    var selected = false
    @State private var hovering = false

    var body: some View {
        HStack(spacing: 10) {
            preview
            Spacer(minLength: 4)
            if entry.pinned { Image(systemName: "pin.fill").font(.system(size: 10)).foregroundStyle(Palette.orange.color) }
            Text(entry.date.formatted(.relative(presentation: .numeric, unitsStyle: .narrow)))
                .font(.system(size: 9.5)).foregroundStyle(.tertiary)
        }
        .padding(.horizontal, 10).padding(.vertical, 8)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous)
            .fill(selected ? Palette.blue.color.opacity(0.22) : Color.primary.opacity(hovering ? 0.07 : 0.03)))
        .contentShape(Rectangle())
        .onHover { hovering = $0 }
        .contextMenu {
            Button(entry.pinned ? "Unpin · Открепить" : "Pin · Закрепить") { store.togglePin(entry) }
            Button("Copy · Копировать") { store.copy(entry) }
            Button("Delete · Удалить", role: .destructive) { store.delete(entry) }
        }
    }

    @ViewBuilder private var preview: some View {
        switch entry.kind {
        case .text:
            Text(entry.text?.trimmingCharacters(in: .whitespacesAndNewlines) ?? "")
                .font(.system(size: 12)).lineLimit(2)
        case .files:
            Label((entry.files ?? []).map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", "), systemImage: "doc.fill")
                .font(.system(size: 12)).lineLimit(1)
        case .image:
            if let url = store.imageURL(for: entry), let image = NSImage(contentsOf: url) {
                Image(nsImage: image).resizable().aspectRatio(contentMode: .fit).frame(maxHeight: 54)
                    .clipShape(RoundedRectangle(cornerRadius: 6, style: .continuous))
            }
        }
    }
}
